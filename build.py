# Chapter id -> title, filled by build() before any prose is rendered, so
# [[id]] wiki-links can resolve to a real page and borrow its title.
CHAPTER_TITLES = {}
CHAPTER_NUMBERS = {}

def slug(s):
    """Anchor id from a heading: lowercase, alphanumerics, single hyphens."""
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return s or "section"

def wikilink(s):
    """Resolve [[id]] / [[id|alias]] to an anchor on the target chapter.

    Written as a separate pass after escaping so the brackets survive. An
    unresolvable target is left as plain text rather than producing a dead link:
    a wrong link is worse than none in a book whose whole claim is traceability.
    """
    def repl(m):
        target = m.group(1).strip()
        alias = m.group(2)
        cid = target
        # Allow a bare number: [[10]] -> 10-kv-cache
        if re.fullmatch(r"\d{1,2}", target):
            matches = [k for k in CHAPTER_TITLES if k.startswith(target.zfill(2) + "-")]
            if len(matches) != 1:
                return m.group(0)
            cid = matches[0]
        if cid not in CHAPTER_TITLES:
            return m.group(0)
        href = cid + ".html"
        text = alias.strip() if alias else CHAPTER_TITLES[cid]
        return f'<a class="xref" href="{href}">{esc(text)}</a>'
    return re.sub(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]", repl, s)

def esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))

def inline(s):
    """Minimal inline markdown: bold, italic, code, wiki-links. Escaped first."""
    s = esc(s)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<em>\1</em>", s)
    s = wikilink(s)
    return s

# A paragraph longer than this is split at a sentence boundary. Two reviewers
# independently named the wall of text as the book's biggest defect: median
# paragraph was 113 words, the longest 441.
MAX_PARA_WORDS = 150

def split_paragraph(text):
    """Break a long paragraph into 2-3 at sentence boundaries.

    Deterministic and lossless: it never rewrites a word, only inserts a break
    after a full stop. A paragraph marked with a trailing <!-- keep --> is left
    alone, because some long paragraphs are meant as one breath.
    """
    if len(text.split()) <= MAX_PARA_WORDS:
        return [text]
    # Split on sentence ends, keeping the delimiter.
    parts = re.split(r"(?<=[.!?])\s+", text)
    if len(parts) < 2:
        return [text]
    out, cur = [], ""
    for s in parts:
        cand = (cur + " " + s).strip() if cur else s
        # Close the paragraph when adding another sentence would pass the cap,
        # but only if the current one has enough substance to stand alone.
        if len(cand.split()) > MAX_PARA_WORDS and len(cur.split()) >= 40:
            out.append(cur)
            cur = s
        else:
            cur = cand
    if cur.strip():
        out.append(cur)
    return out


def paragraphs(text):
    """Split into blocks, keep prose as <p>. No bullets unless the author used them."""
    blocks = [b.strip() for b in re.split(r"\n\s*\n", text) if b.strip()]
    out = []
    headings = []
    for i, b in enumerate(blocks):
        if b.startswith("#") and re.match(r"^#{1,3}\s+\S", b):
            level = len(b) - len(b.lstrip("#"))
            title = b.lstrip("#").strip()
            # The page header already prints the chapter title. Drop the first
            # H1/H2 when it just repeats it; keep later headings.
            if i == 0 and level <= 2:
                continue
            sid = slug(title)
            # Keep ids unique if a chapter repeats a heading.
            seen = {h[1] for h in headings}
            base, n = sid, 2
            while sid in seen:
                sid = f"{base}-{n}"
                n += 1
            headings.append((title, sid))
            out.append(f'<h3 id="{sid}">{inline(title)}</h3>')
            continue
        lines = b.split("\n")
        if all(l.lstrip().startswith(("-", "*")) for l in lines):
            items = "".join(f"<li>{inline(l.lstrip()[1:].strip())}</li>" for l in lines)
            out.append(f"<ul>{items}</ul>")
            continue
        if b.startswith("```"):
            body = re.sub(r"^```\w*\n?|\n?```$", "", b)
            out.append(f"<pre><code>{esc(body)}</code></pre>")
            continue
        # Join wrapped lines inside a paragraph.
        keep = b.rstrip().endswith("<!-- keep -->")
        joined = " ".join(l.strip() for l in lines)
        joined = joined.replace("<!-- keep -->", "").strip()
        chunks = [joined] if keep else split_paragraph(joined)
        for chunk in chunks:
            out.append(f"<p>{inline(chunk)}</p>")
    return "\n".join(out), headings

def mini_toc(headings):
    """An in-chapter contents list, only when it earns its place.

    Two reviewers warned that a TOC on a chapter with one or two subheads is
    clutter, so this is gated at three.
    """
    if len(headings) < 3:
        return ""
    items = "".join(
        f'<li><a href="#{sid}">{esc(t)}</a></li>' for t, sid in headings
    )
    return f'<nav class="mini-toc" aria-label="In this chapter"><h2>In this chapter</h2><ul>{items}</ul></nav>'

def read_chapter(ch):
    p = os.path.join(CHAPTERS, ch["id"] + ".md")
    if not os.path.exists(p):
        return None
    return open(p, encoding="utf-8").read()

# Terms per chapter in the header strip. Past eight the line stops orienting the
# reader and starts reading like an index, so the earliest-defined eight win.
MAX_TERM_CHIPS = 8

def load_glossary():
    """Entries from content/glossary.json, each with its stable anchor slug.

    A missing file is not fatal: the book builds without a glossary, and the
    page simply is not written.
    """
    if not os.path.exists(GLOSSARY):
        return []
    entries = json.load(open(GLOSSARY, encoding="utf-8"))
    for e in entries:
        e["slug"] = slug(e["term"])
    return entries

def term_pattern(e):
    """Compile one entry's matcher, wrapped in word boundaries.

    Substring matching over-hits badly in this book -- 'cache' inside 'caching',
    'token' inside 'tokenizer' -- so every alternative is bounded. The boundary
    is a lookaround rather than \\b so a term ending in punctuation still works.
    """
    alts = e.get("match") or re.escape(e["term"])
    parts = [p.strip() for p in alts.split("|") if p.strip()]
    body = "|".join(f"(?:{p})" for p in parts)
    return re.compile(r"(?<![A-Za-z0-9_])(?:" + body + r")(?![A-Za-z0-9_])", re.I)

def terms_in(text, entries):
    """Glossary entries a chapter uses, earliest first occurrence first.

    Only the first match per entry matters: the chip strip is ordered by where
    the term first appears, so the reader meets the list in reading order.
    """
    found = []
    for e in entries:
        m = term_pattern(e).search(text)
        if m:
            found.append((m.start(), e))
    found.sort(key=lambda t: t[0])
    return [e for _, e in found]

def term_strip(cid, entries):
    """A quiet line of chips naming the terms this chapter uses.

    Muted like the prerequisite strip so it orients without competing with the
    thesis. Each chip links to that term's definition in the glossary.
    """
    txt = read_chapter({"id": cid})
    if not txt:
        return ""
    terms = terms_in(txt, entries)[:MAX_TERM_CHIPS]
    if not terms:
        return ""
    chips = " &middot; ".join(
        f'<a href="../glossary.html#{e["slug"]}">{esc(e["term"])}</a>' for e in terms
    )
    return f'<p class="terms">Terms in this chapter: {chips}</p>'

