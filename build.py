def figure_for(cid):
    """Inline the chapter's SVG figure, rendered by diagrams.py from the planner's spec.

    Inlined rather than referenced so the figure inherits the page's CSS variables
    (--ink, --accent) and prints with the page. The spec's `why` becomes the caption:
    it says what the figure carries, which is more useful than a bare title.
    """
    p = os.path.join(SITE, "figures", cid + ".svg")
    if not os.path.exists(p):
        return ""
    spec = review.load_diagram(cid)
    if not spec:
        return ""
    svg = open(p, encoding="utf-8").read()
    caption = esc(spec.get("why") or spec.get("title") or "")
    title = esc(spec.get("title") or "")
    return f'''
<figure class="chapter-figure">
{svg}
<figcaption><strong>{title}</strong> {caption}</figcaption>
</figure>
'''


def provenance_for(text):
    """List every sourced fact this chapter actually cites, with its origin.

    Built by matching the numbers in the chapter against sources.json, so the
    list cannot drift from the prose. This is the honest version of a footnote
    apparatus: it shows where each measurement came from, not who to cite.
    """
    p = os.path.join(ROOT, "content", "sources.json")
    if not os.path.exists(p):
        return ""
    d = json.load(open(p, encoding="utf-8"))
    used = []
    for v in d["verified"]:
        disp = v["display"]
        # Only count a fact as cited if a distinctive form appears. Short
        # integers like "4" appear in ordinary prose, so require either the
        # full display string or a value with 3+ digits / a decimal point.
        if re.search(r"(?<![\d,.]) " + re.escape(disp) + r"(?![\d])", text):
            used.append(v)
            continue
        val = v["value"]
        if val < 100 and not isinstance(val, float):
            continue
        forms = {f'{val:,}', str(val)}
        if isinstance(val, float):
            forms.add(f'{val:.1f}')
        for f in forms:
            if len(f.replace(",", "").replace(".", "")) < 3:
                continue
            if re.search(r"(?<![\d,.]) " + re.escape(f) + r"(?![\d])", text):
                used.append(v)
                break

    if not used:
        return ""

    rows = "".join(
        f'<tr><td class="pv">{esc(v["display"])}</td>'
        f'<td class="ps">{esc(v["source"])}</td>'
        f'<td class="pc">{esc(v["context"])}</td></tr>'
        for v in used
    )
    return f"""
<section class="provenance">
  <h3>Where these numbers came from</h3>
  <table>
    <thead><tr><th>value</th><th>origin</th><th>what it is</th></tr></thead>
    <tbody>{rows}</tbody>
  </table>
</section>
"""


def build():
    q = json.load(open(QUEUE, encoding="utf-8"))
    meta = q["meta"]
    os.makedirs(SITE, exist_ok=True)

    published = [c for c in q["chapters"] if c["status"] == "published"]
    total_words = 0
    for c in published:
        txt = read_chapter(c)
        if txt:
            total_words += len(re.findall(r"\S+", txt))

    # group chapters by part for the table of contents
    parts = q.get("parts", [])
    by_part = {}
    for c in q["chapters"]:
        by_part.setdefault(c.get("part", ""), []).append(c)

    def toc_items(chapters):
        out = []
        for c in chapters:
            txt = read_chapter(c)
            ok = c["status"] == "published" and txt
            cls = "" if ok else "pending"
            if ok:
                n = len(re.findall(r"\S+", txt))
                status = f"published &middot; {n:,} words"
            else:
                status = c["status"]
            href = f"chapters/{c['id']}.html" if ok else "#"
            out.append(
                f'<li><a class="{cls}" href="{href}">'
                f'<span class="t-num">{c["number"]:02d}</span>'
                f'<span><span class="t-title">{esc(c["title"])}</span>'
                f'<span class="t-status">{status}</span></span>'
                f'</a></li>'
            )
        return "\n".join(out)

    toc_html = []
    for p in parts:
        chs = by_part.get(p, [])
        if not chs:
            continue
        done = sum(1 for c in chs if c["status"] == "published")
        toc_html.append(
            f'<section class="part"><h2 class="part-title">{esc(p)}</h2>'
            f'<p class="part-count">{done} of {len(chs)} written</p>'
            f'<ul class="toc">\n{toc_items(chs)}\n</ul></section>'
        )
    toc_html = "\n".join(toc_html)

    index_body = f"""
<header class="masthead">
  <p class="kicker">Field notes from a two-machine inference pair</p>
  <h1>{esc(meta["project"])}</h1>
  <p class="standfirst">{esc(meta["subtitle"])}</p>
</header>

<section class="frontis">
  <p class="lead drop">A language model is a very large pile of numbers that has been
  arranged, through an expensive and slightly mysterious process, so that it can guess the
  next piece of text. Everything interesting happens in the gap between that sentence and
  the thing actually running on the hardware.</p>

  <p>This book is about that gap. It starts at the character you type and ends at the token
  the sampler picks, and it goes through every layer in between: the tokenizer that chops
  your text into pieces it was trained to recognise, the embedding table that turns those
  pieces into coordinates, the residual stream that every layer reads from and writes to,
  the attention heads that decide which earlier tokens matter, the cache that remembers
  what has already been computed, the mixture-of-experts router that picks which parameters
  to load, the four-bit weights that were squeezed down from sixteen, and the sampler that
  turns a list of scores into one word.</p>

  <p>Each idea in this book arrived at a particular moment to fix a particular problem, and
  the chapters are arranged in that order rather than in the order the code runs. Attention
  was invented in 2014 to stop a recurrent network from forgetting the beginning of a
  sentence. PagedAttention was invented in 2023 because serving systems were wasting most
  of their memory on padding. Grouped-query attention exists because the key-value cache
  outgrew the weights. Knowing what each one replaced is most of knowing what it does.</p>

  <p>The last part grounds the whole thing on two small machines sitting on a desk, because
  an explanation that never touches a real number is not an explanation. But that part is
  the exception. Everything before it would be true on any hardware.</p>

  <hr class="rule-short">
</section>
<hr class="rule-short">
</section>

{figures_panel()}

{toc_html}

<footer class="colophon">
<p>Every figure in this document was read from the live engine, a log line, or a timed
request. The last chapter explains how, so the rest can be checked.</p>
<p><a href="about.html" style="color:var(--accent)">How this was made</a></p>
</footer>
"""
    open(os.path.join(SITE, "index.html"), "w", encoding="utf-8").write(
        page(meta["project"], index_body,
             description=meta.get("subtitle", ""),
             canonical="https://bajpaigaurav.github.io/spark-forge/"))

    about_body = f"""
<header class="masthead">
  <p class="kicker">Colophon</p>
  <h1>How this was made</h1>
  <p class="standfirst">An unattended loop wrote these chapters on the same machines it ends up describing.</p>
</header>

<article class="prose">
<p>The model that wrote this book is a language model, and the last part of the book
describes the machine it runs on. There is no other author.</p>

<p>The loop runs on a twenty-five minute timer. Each tick takes the next chapter from a
queue, writes a draft against a list of what that chapter has to cover, hands the draft to
a second pass instructed to be hostile toward it, rewrites from that report, and submits
the result to two gates. A chapter that clears both is published. One that does not goes
back into the queue. After three failures it is set aside rather than published weak.</p>

<h3>The style gate</h3>
<p>This one is mechanical and unforgiving. It holds a list of words worn smooth by overuse
and a set of sentence shapes that give away a machine: the binary contrast, the colon that
promises a revelation, the participle clause that explains why something matters, the
closing paragraph that summarises what you just read. It also counts em-dashes, because a
writer leaning on them is not thinking. If a draft trips more than its allowance, it fails.</p>

<h3>The fact gate</h3>
<p>This one has two jobs and they are deliberately separate. Published constants &mdash;
vocabulary sizes, model dimensions, paper years, accelerator bandwidths &mdash; must appear
in a curated file with their source, so a chapter can cite 4,096 dimensions or the 2017
transformer without being blocked. Readings from this specific machine must trace to a
separate file captured from the live engine. A chapter cannot invent a plausible-sounding
number in either category. That is the failure mode that makes technical writing
untrustworthy, and it is the one thing the gate is built to stop.</p>

<h3>The critic</h3>
<p>The hostile pass is the part that earns its keep. It is asked to quote passages that
assert a mechanism without showing it, claims that carry numbers or dates without grounding,
formulas stated without a worked calculation, and anything a reader would still not
understand. It catches arithmetic errors and misattributions. On the tokenizer chapter it
noticed that a "twelve years" claim about 1994 to 2016 was actually twenty-two, and that a
coauthor's name was wrong. Neither of those would have survived a human editor either.</p>

<h3>What this costs</h3>
<p>A chapter takes three to eight minutes of machine time, most of it spent before the first
word of output, because the model reasons through the problem before it starts writing. A
chapter that needs three attempts costs three times that.</p>

<h3>What is not automated</h3>
<p>The design of this page is hand-written. The stylesheet, the markup generator, and the two
interactive figures were written by a person, not generated, because a model asked to design
a page produces the same centred column and the same three cards every time. The prose is
the model's. The shape of the thing is not.</p>
</article>

<nav class="chapter-nav">
  <a href="index.html">&larr; Contents</a>
</nav>
"""
    open(os.path.join(SITE, "about.html"), "w", encoding="utf-8").write(
        page("How this was made", about_body,
             description="How the book was written, gated, reviewed and published.",
             canonical="https://bajpaigaurav.github.io/spark-forge/about.html"))

    # Per-chapter pages. Clear stale ones first: a chapter that lost its
    # published status must not keep serving an old page.
    cdir = os.path.join(SITE, "chapters")
    os.makedirs(cdir, exist_ok=True)
    for old in os.listdir(cdir):
        if old.endswith(".html"):
            os.remove(os.path.join(cdir, old))
    ordered = q["chapters"]
    for i, c in enumerate(ordered):
        txt = read_chapter(c)
        if not (c["status"] == "published" and txt):
            continue
        prev_c = ordered[i-1] if i > 0 else None
        next_c = ordered[i+1] if i < len(ordered)-1 else None
        nav = []
        if prev_c:
            nav.append(f'<a href="{prev_c["id"]}.html">&larr; {esc(prev_c["title"])}</a>')
        else:
            nav.append('<a href="../index.html">&larr; Contents</a>')
        if next_c:
            nav.append(f'<a href="{next_c["id"]}.html">{esc(next_c["title"])} &rarr;</a>')
